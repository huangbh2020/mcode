#!/usr/bin/env node
/**
 * Pack the Pi runtime meta-package (@mcode/runtime-pi) for on-demand
 * download.
 *
 * WHY: pi is an in-process ESM library with a ~44MB / 28-package dependency
 * closure. The packaged app no longer bundles it (moved to devDependencies),
 * and runtimeInstaller.ts downloads ONE self-contained tarball instead of
 * resolving the dependency tree at runtime. This script produces that
 * tarball: an npm-shaped package whose tarball root contains a preassembled
 * `node_modules/` with the FULL pi closure in npm's hoisted layout.
 *
 * The closure is produced by a real package manager (`npm install`) against
 * the registry — NOT by walking the local pnpm store — so the artifact is
 * reproducible on any machine/CI and conflict-nesting follows npm's hoisting
 * algorithm.
 *
 * Usage:
 *   cd apps/desktop && node build/pack-pi-runtime.cjs
 * Output:
 *   build/pi-runtime-dist/mcode-pi-runtime-<version>.tgz  (package/ root)
 *   + sha512 integrity (ssri form) printed for verification
 * Publish (maintainer, once per version):
 *   cd build/pi-runtime-dist/package && npm publish --access public
 *   (scope @mcode must exist on npmjs.org; the installer fetches
 *    @mcode/runtime-pi@<version> via registry.npmmirror.com first, which
 *    mirrors npmjs packages automatically)
 */
const { execFileSync } = require("node:child_process");
const { createHash } = require("node:crypto");
const { createReadStream, existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } = require("node:fs");
const { join, resolve } = require("node:path");

const appDir = resolve(__dirname, "..");
const distDir = join(appDir, "build", "pi-runtime-dist");

function piVersion() {
  const pkg = JSON.parse(readFileSync(join(appDir, "package.json"), "utf8"));
  const deps = { ...pkg.dependencies, ...pkg.devDependencies };
  const raw = deps["@earendil-works/pi-coding-agent"];
  if (!raw) throw new Error("@earendil-works/pi-coding-agent not found in apps/desktop/package.json");
  return raw.replace(/^[\^~>=<\s]+/, "");
}

async function sha512Of(file) {
  return new Promise((resolveHash, reject) => {
    const hash = createHash("sha512");
    createReadStream(file)
      .on("data", (c) => hash.update(c))
      .on("error", reject)
      .on("end", () => resolveHash(`sha512-${hash.digest("base64")}`));
  });
}

async function main() {
  const version = piVersion();
  const tar = require("tar");

  rmSync(distDir, { recursive: true, force: true });
  const pkgDir = join(distDir, "package");
  mkdirSync(pkgDir, { recursive: true });
  writeFileSync(
    join(pkgDir, "package.json"),
    JSON.stringify(
      {
        name: "@mcode/runtime-pi",
        version,
        description:
          "Preassembled @earendil-works/pi-coding-agent dependency closure for Mcode's on-demand runtime install. Generated by apps/desktop/build/pack-pi-runtime.cjs — do not edit.",
        private: false,
        license: "MIT",
      },
      null,
      2,
    ) + "\n",
  );

  // Real dependency resolution via npm — hoists the closure into
  // pkgDir/node_modules. --ignore-scripts keeps the build hermetic (no
  // postinstall runs), --omit=dev drops dev-only transitive deps.
  console.log(`[pack-pi-runtime] npm install @earendil-works/pi-coding-agent@${version} ...`);
  execFileSync(
    "npm",
    [
      "install",
      `@earendil-works/pi-coding-agent@${version}`,
      "--ignore-scripts",
      "--omit=dev",
      "--no-audit",
      "--no-fund",
      "--loglevel=error",
      "--no-save",
    ],
    // win32: npm is npm.cmd, and Node >= 18.20 refuses to spawn .cmd without
    // a shell (CVE-2024-27980).
    { cwd: pkgDir, stdio: "inherit", shell: process.platform === "win32" },
  );

  const piRoot = join(pkgDir, "node_modules", "@earendil-works", "pi-coding-agent");
  if (!existsSync(join(piRoot, "package.json"))) {
    throw new Error("install did not produce node_modules/@earendil-works/pi-coding-agent — aborting");
  }

  const outFile = join(distDir, `mcode-pi-runtime-${version}.tgz`);
  await tar.create(
    {
      gzip: true,
      file: outFile,
      cwd: distDir,
      portable: true,
      // npm tarballs normalize ownership/mtime; keep the artifact reproducible
      noPax: true,
    },
    ["package"],
  );

  const integrity = await sha512Of(outFile);
  const sizeMb = (statSync(outFile).size / (1024 * 1024)).toFixed(1);
  console.log(`[pack-pi-runtime] wrote ${outFile} (${sizeMb} MB)`);
  console.log(`[pack-pi-runtime] integrity: ${integrity}`);
  console.log(`[pack-pi-runtime] publish: cd "${join(pkgDir)}" && npm publish --access public`);
}

main().catch((err) => {
  console.error("[pack-pi-runtime] FAILED:", err.message);
  process.exit(1);
});
